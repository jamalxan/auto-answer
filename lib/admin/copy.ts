const PLAN_LABEL: Record<string, string> = { start: "Start", biznes: "Biznes", pro: "Pro", agentlik: "Agentlik" };
export function planLabel(slug: string): string {
  return PLAN_LABEL[slug] ?? slug;
}

const INTL: Record<Locale, string> = { uz: "uz-UZ", ru: "ru-RU", en: "en-US" };
export function fmtNumber(n: number, locale: Locale): string {
  return new Intl.NumberFormat(INTL[locale] ?? "en-US").format(n);
}
export function fmtMoney(n: number, locale: Locale): string {
  return `${fmtNumber(n, locale)} so'm`;
}
export function fmtDate(d: Date, locale: Locale): string {
  return d.toLocaleDateString(INTL[locale] ?? "en-US", { day: "numeric", month: "short", year: "numeric", timeZone: "Asia/Tashkent" });
}
export function fmtDateTime(d: Date, locale: Locale): string {
  return d.toLocaleString(INTL[locale] ?? "en-US", { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit", timeZone: "Asia/Tashkent" });
}
